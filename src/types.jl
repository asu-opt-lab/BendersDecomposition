# ============================================================================
# Core abstract types
# ============================================================================

# ----------------------------------------------------------------------------
# Execution environments
# ----------------------------------------------------------------------------
"""
    AbstractBendersEnv 

Abstract supertype for Benders execution environments.

An execution environment defines the algorithmic strategy used to coordinate the master problem and its oracles. 

See also: [`AbstractBendersSeq`](@ref), [`AbstractBendersBnB`](@ref)
"""
abstract type AbstractBendersEnv end

"""
    AbstractBendersSeq <: AbstractBendersEnv 

Abstract supertype for sequential Benders environments. 
    
Sequential environments repeatedly solve the master problem, query an oracle at the current candidate point, add cuts, and continue until a termination rule is met.
    
See also: [`BendersSeq`](@ref), [`BendersSeqInOut`](@ref)
"""
abstract type AbstractBendersSeq <: AbstractBendersEnv end

"""
    AbstractBendersBnB <: AbstractBendersEnv

Abstract supertype for branch-and-bound Benders environments. 
    
Branch-and-bound environments integrate Benders cut generation into the MIP solver's branch-and-bound process through solver callbacks.
    
See also: [`BendersBnB`](@ref)
"""
abstract type AbstractBendersBnB <: AbstractBendersEnv end

# ----------------------------------------------------------------------------
# Master problems
# ----------------------------------------------------------------------------

"""
    AbstractMaster

Abstract supertype for Benders master problems.

A master owns the optimization model seen by the environment, accepts cuts generated by oracles, and provides candidate solutions for oracle evaluation.

See also: [`Master`](@ref)
"""
abstract type AbstractMaster end

# ----------------------------------------------------------------------------
# Oracles
# ----------------------------------------------------------------------------

"""
    AbstractOracle

Abstract supertype for cut-generating oracles.

An oracle evaluates candidate master solutions and generates valid inequalities through [`generate_cuts`](@ref).

Concrete oracle implementations in BendersX conventionally store their adjustable parameters in a `param` field whose value is a subtype of [`AbstractOracleParam`](@ref).

See also: [`AbstractTypicalOracle`](@ref), [`AbstractDisjunctiveOracle`](@ref)
"""
abstract type AbstractOracle end

"""
    AbstractTypicalOracle <: AbstractOracle

Abstract supertype for typical Benders oracles.

See also: [`ClassicalOracle`](@ref)
"""
abstract type AbstractTypicalOracle <: AbstractOracle end

"""
    AbstractDisjunctiveOracle <: AbstractOracle

Abstract supertype for disjunctive Benders oracles.

Disjunctive oracles generate valid inequalities from disjunctive formulations associated with a candidate master solution.

See also: [`SplitOracle`](@ref)
"""
abstract type AbstractDisjunctiveOracle <: AbstractOracle end

# ----------------------------------------------------------------------------
# Oracle parameters
# ----------------------------------------------------------------------------

"""
    AbstractOracleParam

Abstract supertype for oracle parameter containers.

Oracle parameters collect tolerances and other adjustable settings controlling oracle behavior.

See also: [`BasicOracleParam`](@ref), [`AbstractOracle`](@ref)
"""
abstract type AbstractOracleParam end

# ----------------------------------------------------------------------------
# Problem data
# ----------------------------------------------------------------------------

"""
    AbstractData

Abstract supertype for user-defined problem data.

Concrete subtypes store the coefficients, dimensions, scenario information, and other data required to formulate the master and subproblem models.

See also: [`Master`](@ref), [`ClassicalOracle`](@ref)
"""
abstract type AbstractData end


# ============================================================================
# GBC (Generalized Bound Constraints) Bound Type
# ============================================================================

"""
    GBCBoundType

Sense of a generalized bound constraint (GBC).

The available values are:

- `UpperBound`: `lhs <= rhs`.
- `LowerBound`: `lhs >= rhs`.
- `Fixed`: `lhs == rhs`.
"""
@enum GBCBoundType begin
    UpperBound   # y ≤ f(x)
    LowerBound   # y ≥ f(x)
    Fixed   # y = f(x)
end

# ============================================================================
# Termination Status of Benders Decomposition
# ============================================================================
"""
    TerminationStatus

Abstract supertype for termination statuses of Benders execution environments.
"""
abstract type TerminationStatus end

"""The Benders algorithm has not yet been executed."""
struct NotSolved <: TerminationStatus end

"""The Benders algorithm terminated because the time limit was reached."""
struct TimeLimit <: TerminationStatus end

"""The Benders algorithm terminated successfully."""
struct Optimal <: TerminationStatus end

"""The Benders algorithm terminated because of infeasibility or a numerical issue."""
struct InfeasibleOrNumericalIssue <: TerminationStatus end

